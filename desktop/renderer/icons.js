const aliases = { document: "book", reference: "encyclopedia", other: "file" };
export function icon(name, cls = "") {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("class", `icon${cls ? " " + cls : ""}`);
  // Static, bundled markup only; item data never reaches this.
  svg.innerHTML = paths[aliases[name] || name] || paths.file;
  return svg;
}
/** Replaces `<i data-icon="name">` placeholders written in static HTML. */
export function hydrateIcons(root = document) {
  for (const node of root.querySelectorAll("i[data-icon]"))
    node.replaceWith(icon(node.dataset.icon, node.className));
}
